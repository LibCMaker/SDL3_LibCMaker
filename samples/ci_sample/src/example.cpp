// 2. Игровой цикл: Отрисовка кадра средствами Skia и вывод на видеокарту Intel
SDL_AppResult SDL_AppIterate(void* appstate) {
    AppState* state = (AppState*)appstate;
    SkCanvas* canvas = state->skiaSurface->getCanvas();

    // --- РИСОВАНИЕ СРЕДСТВАМИ SKIA ---
    canvas->clear(SkColors::kDkGray); // Наш темно-серый цвет фона

    SkPaint paint;
    paint.setAntiAlias(true); // Включаем идеальное сглаживание Skia
    paint.setColor(SkColorSetRGB(0, 229, 255)); // Неоново-бирюзовый цвет под стиль KDE

    // Создаем красивый эффект пульсации круга
    float time = SDL_GetTicks() / 1000.0f;
    float pulse = 120.0f + SDL_sinf(time * 4.0f) * 20.0f;

    canvas->drawCircle(state->width / 2.0f, state->height / 2.0f, pulse, paint);
    // ---------------------------------

    // Аппаратно копируем измененные пиксели из Skia холста прямо в текстуру видеокарты
    SDL_UpdateTexture(state->texture, NULL, state->sdlSurface->pixels, state->sdlSurface->pitch);

    // Очищаем видеобуфер окна и мгновенно выводим готовую текстуру на дисплей X11
    SDL_RenderClear(state->renderer);
    SDL_RenderTexture(state->renderer, state->texture, NULL, NULL);
    SDL_RenderPresent(state->renderer);

    return SDL_APP_CONTINUE;
}

// 3. Обработка системных событий KDE / X11
SDL_AppResult SDL_AppEvent(void* appstate, SDL_Event* event) {
    if (event->type == SDL_EVENT_QUIT) {
        return SDL_APP_SUCCESS; // Корректное завершение работы
    }
    return SDL_APP_CONTINUE;
}

// 4. Очистка выделенной памяти
void SDL_AppQuit(void* appstate, SDL_AppResult result) {
    if (appstate) {
        AppState* state = (AppState*)appstate;

        // Сначала строго сбрасываем Skia, пока жива sdlSurface
        state->skiaSurface.reset();

        if (state->texture) SDL_DestroyTexture(state->texture);
        if (state->sdlSurface) SDL_DestroySurface(state->sdlSurface);
        if (state->renderer) SDL_DestroyRenderer(state->renderer);
        if (state->window) SDL_DestroyWindow(state->window);

        delete state;
    }
    SDL_Quit();
}






